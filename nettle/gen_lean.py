"""Write lean/NettleSalsa20/Program.lean from the linked ELF: its loaded image, from address 0.

The image is .text followed by .rodata (the strings of Nettle's assert), zero-padded between
them and to a whole word.
"""
from pathlib import Path
import struct
import sys

HERE = Path(__file__).resolve().parent
ELF = HERE / 'build/nettle_salsa20.elf'
OUT = HERE / 'lean/NettleSalsa20/Program.lean'
SHF_ALLOC = 2
SHT_NOBITS = 8


def symbols_and_image(data):
  """The symbol table, and the bytes of every allocated section placed at their addresses."""
  shoff, = struct.unpack_from('<Q', data, 40)
  shentsize, shnum, shstrndx = struct.unpack_from('<HHH', data, 58)
  sections = [struct.unpack_from('<IIQQQQIIQQ', data, shoff + i * shentsize) for i in range(shnum)]
  names = sections[shstrndx]
  def name(off, table):
    end = data.index(b'\0', table + off)
    return data[table + off:end].decode()
  by_name = {name(s[0], names[4]): s for s in sections}
  loaded = {n: s for n, s in by_name.items() if s[2] & SHF_ALLOC and s[5]}
  assert set(loaded) == {'.text', '.rodata'}, f'unexpected sections {sorted(loaded)}'
  assert by_name['.text'][3] == 0, '.text must start at address 0'
  assert all(s[1] != SHT_NOBITS for s in loaded.values())
  end = max(s[3] + s[5] for s in loaded.values())
  image = bytearray(-(-end // 4) * 4)
  for s in loaded.values():
    image[s[3]:s[3] + s[5]] = data[s[4]:s[4] + s[5]]
  symtab, strtab = by_name['.symtab'], by_name['.strtab']
  syms = {}
  for off in range(symtab[4], symtab[4] + symtab[5], 24):
    st_name, _, _, _, value, size = struct.unpack_from('<IBBHQQ', data, off)
    syms[name(st_name, strtab[4])] = (value, size)
  return syms, bytes(image)


def main():
  syms, image = symbols_and_image(ELF.read_bytes())
  entry, _ = syms['_nettle_salsa20_core']
  assert entry == 0xc0, 'the library code must follow the driver'
  words = struct.unpack(f'<{len(image) // 4}I', image)
  def block(ws):
    rows = [', '.join(f'0x{w:08x}' for w in ws[i:i + 6]) for i in range(0, len(ws), 6)]
    return '[\n  ' + ',\n  '.join(rows) + ']'
  OUT.write_text(f'''import TinyFive.Machine

/-!
# The linked Nettle Salsa20 program

Generated by `nettle/gen_lean.py` from `nettle/build/nettle_salsa20.elf`: its loaded image from
address 0. It holds the driver of `nettle/start.S`; then, from `coreEntry`, the RV64IM code GCC
produced for `vendor/salsa20-core-internal.c` (`_nettle_salsa20_core`), `__assert_func` of
`nettle/assert.S`, picolibc's `memcpy`, and the `.rodata` of Nettle's assert strings.
-/
namespace NettleSalsa20
open TinyFive

/-- The driver `_start`, at address 0. -/
def driverWords : List (BitVec 32) := {block(words[:entry // 4])}

/-- The address of `_nettle_salsa20_core`. -/
def coreEntry : Nat := {entry:#x}

/-- Everything linked after the driver, from `coreEntry`. -/
def coreWords : List (BitVec 32) := {block(words[entry // 4:])}

def prog : List (BitVec 32) := driverWords ++ coreWords

/-- One mebibyte of memory, as for the linked fixture. -/
def memSize : Nat := 0x100000

def initial : Machine 64 := load 64 prog memSize []

end NettleSalsa20
''')


if __name__ == '__main__':
  sys.exit(main())
