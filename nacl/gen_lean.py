"""Write the Program files of lean/NaClSalsa20 from the linked ELFs: every .text word, from address 0."""
from pathlib import Path
import struct
import sys

HERE = Path(__file__).resolve().parent
# (primitive, Lean module, namespace)
PROGRAMS = [('salsa20', 'Program', 'NaClSalsa20'),
            ('hsalsa20', 'HSalsa20Program', 'NaClSalsa20.HSalsa20')]


def symbols_and_text(data):
  shoff, = struct.unpack_from('<Q', data, 40)
  shentsize, shnum, shstrndx = struct.unpack_from('<HHH', data, 58)
  sections = [struct.unpack_from('<IIQQQQIIQQ', data, shoff + i * shentsize) for i in range(shnum)]
  names = sections[shstrndx]
  def name(off, table):
    end = data.index(b'\0', table + off)
    return data[table + off:end].decode()
  by_name = {name(s[0], names[4]): s for s in sections}
  text = by_name['.text']
  assert text[3] == 0, '.text must start at address 0'
  code = data[text[4]:text[4] + text[5]]
  symtab, strtab = by_name['.symtab'], by_name['.strtab']
  syms = {}
  for off in range(symtab[4], symtab[4] + symtab[5], 24):
    st_name, _, _, _, value, size = struct.unpack_from('<IBBHQQ', data, off)
    syms[name(st_name, strtab[4])] = (value, size)
  return syms, code


def write(primitive, module, namespace):
  elf = HERE / f'build/nacl_{primitive}.elf'
  syms, code = symbols_and_text(elf.read_bytes())
  entry, size = syms[f'crypto_core_{primitive}_ref']
  assert entry + size == len(code), f'crypto_core_{primitive}_ref must end .text'
  words = struct.unpack(f'<{len(code) // 4}I', code)
  def block(ws):
    rows = [', '.join(f'0x{w:08x}' for w in ws[i:i + 6]) for i in range(0, len(ws), 6)]
    return '[\n  ' + ',\n  '.join(rows) + ']'
  driver = 'start.S' if primitive == 'salsa20' else f'start_{primitive}.S'
  title = {'salsa20': 'Salsa20', 'hsalsa20': 'HSalsa20'}[primitive]
  (HERE / f'lean/NaClSalsa20/{module}.lean').write_text(f'''import TinyFive.Machine

/-!
# The linked NaCl {title} program

Generated by `nacl/gen_lean.py` from `nacl/build/nacl_{primitive}.elf`: the `.text` section, which
starts at address 0. It holds the driver of `nacl/{driver}`, then `crypto_core_{primitive}_ref`, the
RV64IM code GCC produced for `vendor/crypto_core/{primitive}/ref/core.c`.
-/
namespace {namespace}
open TinyFive

/-- The driver `_start`, at address 0. -/
def driverWords : List (BitVec 32) := {block(words[:entry // 4])}

/-- The address of `crypto_core_{primitive}_ref`. -/
def coreEntry : Nat := {entry:#x}

/-- `crypto_core_{primitive}_ref`, at `coreEntry`. -/
def coreWords : List (BitVec 32) := {block(words[entry // 4:])}

def prog : List (BitVec 32) := driverWords ++ coreWords

/-- One mebibyte of memory, as for the linked fixture. -/
def memSize : Nat := 0x100000

def initial : Machine 64 := load 64 prog memSize []

end {namespace}
''')



def main():
  for program in PROGRAMS:
    write(*program)

if __name__ == '__main__':
  sys.exit(main())
