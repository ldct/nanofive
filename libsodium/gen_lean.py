"""Write lean/LibsodiumSalsa20/Program.lean from the linked ELF: every .text word, from address 0."""
from pathlib import Path
import struct
import sys

HERE = Path(__file__).resolve().parent
ELF = HERE / 'build/libsodium_salsa20.elf'
OUT = HERE / 'lean/LibsodiumSalsa20/Program.lean'


def symbols_and_text(data):
  shoff, = struct.unpack_from('<Q', data, 40)
  shentsize, shnum, shstrndx = struct.unpack_from('<HHH', data, 58)
  sections = [struct.unpack_from('<IIQQQQIIQQ', data, shoff + i * shentsize) for i in range(shnum)]
  names = sections[shstrndx]
  def name(off, table):
    end = data.index(b'\0', table + off)
    return data[table + off:end].decode()
  by_name = {name(s[0], names[4]): s for s in sections}
  text = by_name['.text']
  assert text[3] == 0, '.text must start at address 0'
  code = data[text[4]:text[4] + text[5]]
  symtab, strtab = by_name['.symtab'], by_name['.strtab']
  syms = {}
  for off in range(symtab[4], symtab[4] + symtab[5], 24):
    st_name, _, _, _, value, size = struct.unpack_from('<IBBHQQ', data, off)
    syms[name(st_name, strtab[4])] = (value, size)
  return syms, code


def main():
  syms, code = symbols_and_text(ELF.read_bytes())
  start = syms['crypto_core_salsa'][0]
  entry, size = syms['crypto_core_salsa20']
  assert start == 0x84, 'the library code must follow the driver'
  assert start < entry and entry + size == len(code), 'crypto_core_salsa20 must end .text'
  words = struct.unpack(f'<{len(code) // 4}I', code)
  def block(ws):
    rows = [', '.join(f'0x{w:08x}' for w in ws[i:i + 6]) for i in range(0, len(ws), 6)]
    return '[\n  ' + ',\n  '.join(rows) + ']'
  OUT.write_text(f'''import TinyFive.Machine

/-!
# The linked libsodium Salsa20 program

Generated by `libsodium/gen_lean.py` from `libsodium/build/libsodium_salsa20.elf`: the `.text`
section, which starts at address 0. It holds the driver of `libsodium/start.S`, then the RV64IM
code GCC produced for `vendor/src/libsodium/crypto_core/salsa/ref/core_salsa_ref.c`: the static
`crypto_core_salsa`, at `coreStart`, and `crypto_core_salsa20`, which calls it with 20 rounds,
at `coreEntry`.
-/
namespace LibsodiumSalsa20
open TinyFive

/-- The driver `_start`, at address 0. -/
def driverWords : List (BitVec 32) := {block(words[:start // 4])}

/-- The address of `crypto_core_salsa`, the start of the library code. -/
def coreStart : Nat := {start:#x}

/-- The address of `crypto_core_salsa20`. -/
def coreEntry : Nat := {entry:#x}

/-- `crypto_core_salsa` and `crypto_core_salsa20`, from `coreStart`. -/
def coreWords : List (BitVec 32) := {block(words[start // 4:])}

def prog : List (BitVec 32) := driverWords ++ coreWords

/-- One mebibyte of memory, as for the linked fixture. -/
def memSize : Nat := 0x100000

def initial : Machine 64 := load 64 prog memSize []

end LibsodiumSalsa20
''')

if __name__ == '__main__':
  sys.exit(main())
